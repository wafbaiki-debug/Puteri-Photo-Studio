const fs = require('fs');
const path = require('path');
const unzipper = require('unzipper');

const root = __dirname;
const archivePath = path.join(root, 'Puteri-Photo-Studio-GitHub-Upload-v1.8.5.zip');
const outputDir = path.join(root, 'dist');

const supabaseUrl = (process.env.SUPABASE_URL || '').trim();
const supabaseAnonKey = (process.env.SUPABASE_ANON_KEY || process.env.SUPABASE_PUBLISHABLE_KEY || '').trim();
const pushVapidPublicKey = (process.env.VAPID_PUBLIC_KEY || process.env.PUSH_VAPID_PUBLIC_KEY || '').trim();

if (!supabaseUrl || !/^https:\/\/[a-zA-Z0-9-]+\.supabase\.co$/.test(supabaseUrl)) {
  console.error('BUILD STOPPED: Set SUPABASE_URL in Vercel Production Environment Variables.');
  process.exit(1);
}
if (!supabaseAnonKey) {
  console.error('BUILD STOPPED: Set SUPABASE_ANON_KEY (or SUPABASE_PUBLISHABLE_KEY) in Vercel Production Environment Variables.');
  process.exit(1);
}
if (!pushVapidPublicKey || !/^[A-Za-z0-9_-]{80,100}$/.test(pushVapidPublicKey)) {
  console.error('BUILD STOPPED: Set VAPID_PUBLIC_KEY (or PUSH_VAPID_PUBLIC_KEY) to the VAPID PUBLIC key only. Never use the private key here.');
  process.exit(1);
}
if (!fs.existsSync(archivePath)) {
  console.error('BUILD STOPPED: The v1.8.5 web source ZIP is missing from the repository root.');
  process.exit(1);
}

const allowed = new Set([
  'index.html', 'manifest.webmanifest', 'sw.js', 'icon.svg',
  'icon-192.png', 'icon-512.png', 'apple-touch-icon.png',
  'logo-puteri-suhaimi.png', 'robots.txt'
]);

function writeEntry(entry, destination) {
  return new Promise((resolve, reject) => {
    const output = fs.createWriteStream(destination);
    entry.stream().pipe(output);
    output.on('finish', resolve);
    output.on('error', reject);
  });
}

async function main() {
  fs.rmSync(outputDir, { recursive: true, force: true });
  fs.mkdirSync(outputDir, { recursive: true });
  const archive = await unzipper.Open.file(archivePath);
  const extracted = new Set();
  for (const entry of archive.files) {
    const name = entry.path.replace(/\\/g, '/');
    if (entry.type !== 'File' || !allowed.has(name)) continue;
    const destination = path.join(outputDir, name);
    await writeEntry(entry, destination);
    extracted.add(name);
  }
  for (const required of ['index.html', 'manifest.webmanifest', 'sw.js']) {
    if (!extracted.has(required)) throw new Error(`Required web asset missing: ${required}`);
  }
  const browserConfig = { supabaseUrl, supabaseAnonKey, pushVapidPublicKey, demoMode: false };
  fs.writeFileSync(path.join(outputDir, 'config.js'),
    `// Generated by Vercel build. Public values only.\nwindow.STUDIO_CONFIG = ${JSON.stringify(browserConfig, null, 2)};\n`, 'utf8');
  console.log('Puteri Photo Studio v1.8.5 frontend build completed.');
  console.log('Customer push opt-in UI and admin device-owner UI are included in index.html.');
}
main().catch((error) => { console.error('BUILD FAILED:', error.message || error); process.exit(1); });
